// Summarizes results/measurements.csv and results/k6_*.json into
//   results/summary.md                    (readable table: mean ± standard deviation)
//   report/generated/results_table.tex    (LaTeX table for the report)
//   report/generated/chart_data.dat       (data for the pgfplots charts)
// Usage (from the project root): node scripts/summarize.js
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const resDir = path.join(root, 'results');
const genDir = path.join(root, 'report', 'generated');
fs.mkdirSync(genDir, { recursive: true });

// values[target][metric] = [numbers...]
const values = {};
const units = {};
function add(target, metric, v, unit) {
  if (v === undefined || v === null || Number.isNaN(v)) return;
  ((values[target] ||= {})[metric] ||= []).push(v);
  units[metric] = unit;
}

const csvPath = path.join(resDir, 'measurements.csv');
if (!fs.existsSync(csvPath)) {
  console.error('No results/measurements.csv yet. Run scripts/measure.ps1 first.');
  process.exit(1);
}
for (const line of fs.readFileSync(csvPath, 'utf8').trim().split(/\r?\n/).slice(1)) {
  const [, target, , metric, value, unit] = line.split(',');
  add(target, metric, parseFloat(value), unit);
}

for (const f of fs.readdirSync(resDir).filter((f) => /^k6_(docker|vm)_run\d+\.json$/.test(f))) {
  const target = f.split('_')[1];
  const m = JSON.parse(fs.readFileSync(path.join(resDir, f), 'utf8')).metrics;
  add(target, 'latency_median', m.http_req_duration.med, 'ms');
  add(target, 'latency_p95', m.http_req_duration['p(95)'], 'ms');
  add(target, 'throughput', m.http_reqs.rate, 'req/s');
  add(target, 'error_rate', (m.http_req_failed?.value ?? 0) * 100, '%');
}

const mean = (a) => a.reduce((s, x) => s + x, 0) / a.length;
const sd = (a) => (a.length < 2 ? 0 : Math.sqrt(a.reduce((s, x) => s + (x - mean(a)) ** 2, 0) / (a.length - 1)));
const fmt = (x) => (Math.abs(x) >= 100 ? x.toFixed(0) : x.toFixed(1));
const cell = (t, k) => {
  const a = values[t]?.[k];
  if (!a || !a.length) return '--';
  const f = k === 'error_rate' ? (x) => x.toFixed(2) : fmt; // small percentages need 2 decimals
  return a.length > 1 ? `${f(mean(a))} ± ${f(sd(a))}` : f(a[0]);
};

const order = [
  ['disk_size', 'Disk footprint'],
  ['start_time', 'Start time (cold)'],
  ['resume_time', 'Start time (warm / resume)'],
  ['stop_time', 'Stop time'],
  ['app_rss_idle', 'App process memory, idle'],
  ['platform_mem_idle', 'Platform memory, idle'],
  ['platform_mem_load', 'Platform memory, under load'],
  ['docker_backend_mem_idle', 'Docker backend VM memory, idle'],
  ['latency_median', 'Response time, median'],
  ['latency_p95', 'Response time, p95'],
  ['throughput', 'Throughput'],
  ['error_rate', 'Failed requests'],
];
const targets = ['vm', 'docker'];
const n = (t) => Math.max(0, ...Object.values(values[t] || {}).map((a) => a.length));

// Markdown
let md = `# Results summary (mean ± sample standard deviation)\n\nRuns: VM = ${n('vm')}, Docker = ${n('docker')}\n\n`;
md += '| Metric | Unit | VM | Docker | VM / Docker |\n|---|---|---|---|---|\n';
for (const [k, label] of order) {
  if (!targets.some((t) => values[t]?.[k])) continue;
  const v = values.vm?.[k], d = values.docker?.[k];
  const ratio = v && d && mean(d) !== 0 ? (mean(v) / mean(d)).toFixed(1) + '×' : '--';
  md += `| ${label} | ${units[k]} | ${cell('vm', k)} | ${cell('docker', k)} | ${ratio} |\n`;
}
fs.writeFileSync(path.join(resDir, 'summary.md'), md);

// LaTeX table
const tex = (s) => s.replace('±', '$\\pm$').replace('%', '\\%');
let t = '% Generated by scripts/summarize.js -- do not edit by hand\n';
t += '\\begin{table}[htbp]\n\\caption{Measured Results (Mean $\\pm$ Standard Deviation, ' + `${Math.min(n('vm'), n('docker'))} Runs)}\n`;
t += '\\label{tab:results}\n\\centering\n\\footnotesize\n\\resizebox{\\columnwidth}{!}{%\n\\begin{tabular}{|l|c|c|c|}\n\\hline\n';
t += '\\textbf{Metric} & \\textbf{Unit} & \\textbf{VM} & \\textbf{Container} \\\\\n\\hline\n';
for (const [k, label] of order) {
  if (!targets.some((x) => values[x]?.[k])) continue;
  t += `${label} & ${tex(units[k])} & ${tex(cell('vm', k))} & ${tex(cell('docker', k))} \\\\\n\\hline\n`;
}
t += '\\end{tabular}}\n\\end{table}\n';
fs.writeFileSync(path.join(genDir, 'results_table.tex'), t);

// Chart data: one row per metric, mean and sd for each target.
const chartKeys = ['start_time', 'resume_time', 'platform_mem_idle', 'latency_median', 'latency_p95', 'throughput', 'disk_size'];
let dat = 'metric vm_mean vm_sd docker_mean docker_sd\n';
for (const k of chartKeys) {
  const v = values.vm?.[k] || [], d = values.docker?.[k] || [];
  const f = (a, fn) => (a.length ? fn(a).toFixed(3) : 'nan');
  dat += `${k} ${f(v, mean)} ${f(v, sd)} ${f(d, mean)} ${f(d, sd)}\n`;
}
fs.writeFileSync(path.join(genDir, 'chart_data.dat'), dat);

// Start-time chart data (seconds), used by the bar chart in the report.
let st = 'phase vm vmsd docker dockersd\n';
for (const [k, label] of [['start_time', 'cold'], ['resume_time', 'warm']]) {
  const v = values.vm?.[k] || [], d = values.docker?.[k] || [];
  const f = (a, fn) => (a.length ? (fn(a) / 1000).toFixed(3) : '0');
  st += `${label} ${f(v, mean)} ${f(v, sd)} ${f(d, mean)} ${f(d, sd)}\n`;
}
fs.writeFileSync(path.join(genDir, 'chart_start.dat'), st);

console.log(md);
console.log('Wrote results/summary.md, report/generated/results_table.tex, report/generated/chart_data.dat');
